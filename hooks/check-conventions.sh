#!/usr/bin/env bash
#
# Checks a file the session just wrote against the conventions the repository declared, and reports
# what is missing back to the model.
#
# Two rules, both readable straight out of a file: every declaration carries a doc comment, and no
# line matches a pattern the repository has forbidden. Nothing else here is enforceable by reading,
# and a convention checker that guesses is worse than none.
#
# Runs on PostToolUse, not before the write. The write has already happened, so nothing is undone —
# the exit code only puts the finding in front of the model while the file is still the thing it is
# working on. Upstream this ran at the end of a session instead, which meant a missing doc comment
# surfaced after the context that would have made writing it cheap was gone.
#
# Entirely opt-in: with no `conventions` block in .claude/harness.json this exits 0 without reading
# anything. A convention checker that arrives with opinions nobody asked for is the kind of guard
# that gets uninstalled along with everything shipped beside it.
#
# Configuration, all keys optional:
#
#   "conventions": {
#     "docComments": true,
#     "skip": ["/generated/"],
#     "generatedBanners": ["auto-generated by openapi-typescript"],
#     "forbiddenText": { "pattern": "[àáảãạ…]", "label": "non-English text in code" }
#   }
#
# Exit 0 when clean or not configured, 2 when something is reported.

set -uo pipefail

HOOK_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=/dev/null
source "$HOOK_DIR/lib-hook-log.sh"
# shellcheck source=/dev/null
source "$HOOK_DIR/lib-sensitive-paths.sh"

INPUT=$(cat)
[[ -n "$INPUT" ]] || exit 0

TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // empty' 2>/dev/null)
case "$TOOL" in
  Edit | Write | NotebookEdit) ;;
  *) exit 0 ;;
esac

SESSION=$(printf '%s' "$INPUT" | jq -r '.session_id // "-"' 2>/dev/null)
SESSION=$(printf '%s' "$SESSION" | tr -c 'a-zA-Z0-9_-' '_')

FILE=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // .tool_input.path // empty' 2>/dev/null)
[[ -n "$FILE" && -f "$FILE" ]] || exit 0

# Resolved from the environment first, then from the file's own repository — never from the shell's
# cwd, which is where the first version got it wrong. This hook runs after the write and the session
# may sit anywhere; asking git in the current directory answered with whichever repository the
# terminal happened to be in, so the configuration was looked up in the wrong tree and every check
# silently passed.
ROOT="${CLAUDE_PROJECT_DIR:-}"
if [[ -z "$ROOT" || ! -d "$ROOT" ]]; then
  ROOT=$(git -C "$(dirname "$FILE")" rev-parse --git-common-dir 2>/dev/null || true)
  [[ "$ROOT" = /* ]] || ROOT="$(dirname "$FILE")/${ROOT#./}"
  ROOT="${ROOT%/.git}"
fi
[[ -n "$ROOT" && -d "$ROOT" ]] || ROOT="$PWD"

CONFIG=$(harness_config_path "$ROOT")
[[ -f "$CONFIG" ]] || exit 0
# A fast path, not the opt-in itself. With no `conventions` block every rule below is unconfigured
# and reports nothing, so removing this line changes no verdict — it only stops a python process
# from starting on every write in a repository that never asked for the check. Said plainly because
# the mutation run proved it: deleting this line leaves the suite green, and a line no test can kill
# should say why it is still here.
jq -e '.conventions' "$CONFIG" > /dev/null 2>&1 || exit 0

command -v python3 > /dev/null 2>&1 || {
  echo "check-conventions: python3 not found, conventions were not checked." >&2
  exit 0
}

REPORT=$(python3 - "$CONFIG" "$FILE" "$(sensitive_relpath "$FILE" "$ROOT")" <<'PY'
import json
import re
import sys
from pathlib import Path

config = json.loads(Path(sys.argv[1]).read_text(encoding='utf-8'))
conventions = config.get('conventions') or {}
path = Path(sys.argv[2])
label = sys.argv[3]

# Build output and vendored code, which is nobody's to document. Extended, not replaced, by the
# repository: these directories mean the same thing everywhere, and a repository that has to restate
# them will get one wrong.
SKIP = [r'/obj/', r'/bin/', r'/dist/', r'/coverage/', r'node_modules', r'/\.wrangler/',
        r'/TestResults/', r'\.d\.ts$']
SKIP += [str(s) for s in conventions.get('skip', [])]
if any(re.search(p, str(path)) for p in SKIP):
    sys.exit(0)

if path.suffix not in ('.cs', '.ts', '.tsx'):
    sys.exit(0)

lines = path.read_text(encoding='utf-8', errors='replace').split('\n')

# Generated files are exempt by what they say, not by where they sit. Naming the paths is how the
# upstream version failed: the same generator wrote a second file nobody added to the list, and the
# gate demanded doc comments that the next generator run would erase. Matched in the head of the
# file only, so a hand-written module that mentions the generator in prose does not exempt itself.
BANNERS = [str(b) for b in conventions.get('generatedBanners', [])]
if BANNERS and any(re.search(b, l, re.IGNORECASE) for l in lines[:10] for b in BANNERS):
    sys.exit(0)

findings = []

forbidden = conventions.get('forbiddenText') or {}
pattern = forbidden.get('pattern')
if pattern:
    what = forbidden.get('label', 'forbidden text in code')
    rx = re.compile(pattern)
    for i, line in enumerate(lines):
        if rx.search(line):
            findings.append((i + 1, what, line.strip()[:80]))

# Doc comments are required in shipped code, not in test suites: a test name here is a whole
# sentence, and a comment above one restates it — the thing a doc comment is not for.
TESTS = re.compile(r'(^|/)(tests?)/')
CSHARP_MEMBER = re.compile(r'^(public|internal|protected|private)\s')

if conventions.get('docComments') and not TESTS.search(str(path)):
    if path.suffix == '.cs':
        for i, line in enumerate(lines):
            stripped = line.strip()
            if not CSHARP_MEMBER.match(stripped):
                continue
            # A local declaration inside a body is not a member; a member line always ends in a
            # signature, a block, or an expression body.
            if ('(' not in stripped and '{' not in stripped
                    and '=>' not in stripped and ';' not in stripped):
                continue
            j = i - 1
            while j >= 0 and (lines[j].strip().startswith('[') or not lines[j].strip()):
                j -= 1
            if j < 0 or not lines[j].strip().startswith('///'):
                findings.append((i + 1, 'missing /// doc comment', stripped[:80]))
    else:
        for i, line in enumerate(lines):
            if not line.startswith('export'):
                continue
            # A re-export carries its documentation at the definition, not here.
            if re.match(r'^export\s+(\*|\{|default\s+\w+\s*;)', line):
                continue
            j = i - 1
            while j >= 0 and not lines[j].strip():
                j -= 1
            if j < 0 or not lines[j].strip().endswith('*/'):
                findings.append((i + 1, 'missing /** TSDoc */', line.strip()[:80]))

if not findings:
    sys.exit(0)

for line, what, snippet in findings:
    print(f"{label}:{line}: {what}\n    {snippet}")
print(f"\n{len(findings)} convention violation(s) in the file just written. "
      "These are declared in .claude/harness.json, so they are this repository's rules, not the "
      "plugin's. Fix them now, while the file is still the thing being worked on.")
sys.exit(1)
PY
)
STATUS=$?

if [[ $STATUS -eq 0 ]]; then
  exit 0
fi

hook_log check-conventions "$SESSION" "$TOOL" block "$(sensitive_relpath "$FILE" "$ROOT")" conventions
printf '%s\n' "$REPORT" >&2
exit 2
